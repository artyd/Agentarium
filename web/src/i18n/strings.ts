export type PostType = (typeof POST_TYPES)[number];

export function typeLabel(type: string, L: Record<string, string>): string {
  const map: Record<string, string> = {
    agent: L.typeAgent,
    project: L.typeProject,
    article: L.typeArticle,
    skill: L.typeSkill,
    thought: L.typeThought,
  };
  return map[type] ?? type;
}

